"""Regenerate notes/OCCUPATION-REVIEW-CHECKPOINT.md from the index and batches.json."""
import json, collections, subprocess, pathlib
from common import ROOT, load_index
REVIEWED = "individually reviewed: advantage, alternatives, resources, qualification and adaptation authored; mechanical grants unchanged"
here = pathlib.Path(__file__).parent
log = json.loads((here / "batches.json").read_text())
data = load_index(); prof = data["profiles"]
done = [p for p in prof if p["sourcebook"].get("status") == REVIEWED]
rest = [p for p in prof if p["sourcebook"].get("status") != REVIEWED]
val = subprocess.run(["python3", str(here / "validate.py")], capture_output=True, text=True, cwd=ROOT).stdout.strip().splitlines()
def ranges(ids):
    nums = sorted(int(i[2:]) for i in ids); out = []; s = prev = None
    for n in nums:
        if s is None: s = prev = n
        elif n == prev + 1: prev = n
        else: out.append((s, prev)); s = prev = n
    if s is not None: out.append((s, prev))
    return ", ".join(f"O-{a:03d}" if a == b else f"O-{a:03d}–O-{b:03d}" for a, b in out) or "none"
fam = collections.Counter(p["family"] for p in rest)
lines = ["# Section 6.5 occupation review — persistent checkpoint", "",
         "Generated by `tools/occupation_review/checkpoint.py`; do not edit by hand. Resume from **Exact next task**.", "",
         f"- Total profiles: {len(prof)}", f"- Individually reviewed to the full Section 6.5 standard: {len(done)}",
         f"- Remaining: {len(rest)}", "",
         "## Completed profile IDs", "", ranges([p["id"] for p in done]), "",
         "## Remaining profile IDs", "", ranges([p["id"] for p in rest]), "",
         "Remaining by family: " + (", ".join(f"{k} {v}" for k, v in sorted(fam.items())) or "none"), "",
         "## Batch log", "", "| Batch | Profiles | Families | Commit |", "|---|---|---|---|"]
for b in log["batches"]:
    lines.append(f"| {b['id']} | {b['profiles']} | {b['families']} | {b.get('commit', 'this commit')} |")
lines += ["", "## Latest validation (`python3 tools/occupation_review/validate.py`)", "", "```"] + val[-6:] + ["```", "",
          "## Unresolved issues", ""] + [f"- {u}" for u in log.get("unresolved", [])] + ["", "## Exact next task", "", log["next"], ""]
(ROOT / "notes" / "OCCUPATION-REVIEW-CHECKPOINT.md").write_text("\n".join(lines))
print("checkpoint written")
